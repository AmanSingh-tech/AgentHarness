// Generates src/theme.css: every palette the dashboard uses becomes CSS variables with a light theme
// (Tailwind's own values) and a dark theme (derived), so existing utility classes theme themselves.
// Run: node scripts/gen-theme.mjs
import colors from "tailwindcss/colors.js";
import { writeFileSync } from "node:fs";

const PALETTES = ["emerald", "rose", "amber", "sky", "violet", "orange", "yellow", "teal", "indigo"];
const SHADES = [50, 100, 200, 300, 400, 500, 600, 700, 800, 900];
const DARK_BG = [18, 18, 18];

const rgb = (hex) => [1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16));
const mix = (a, b, t) => a.map((v, i) => Math.round(v * t + b[i] * (1 - t)));
const triple = (c) => c.join(" ");

// Neutrals: the showcase site's palette (warm off-white light theme, near-black dark theme).
const slateLight = ["#f4f5fa", "#eceef6", "#e1e3ee", "#cfd2e2", "#9a9db6", "#64698b", "#4c5070", "#363a54", "#22253a", "#121212"];
const slateDark = ["#1d1d21", "#242429", "#2d2d33", "#3c3c44", "#6e7187", "#a3a6c1", "#b9bbcf", "#cfd1df", "#e2e3ed", "#f1f2f9"];

const light = [], dark = [];
SHADES.forEach((s, i) => {
  light.push(`--slate-${s}: ${triple(rgb(slateLight[i]))};`);
  dark.push(`--slate-${s}: ${triple(rgb(slateDark[i]))};`);
});
for (const name of PALETTES) {
  const p = Object.fromEntries(SHADES.map((s) => [s, rgb(colors[name][s])]));
  const d = {
    50: mix(p[500], DARK_BG, 0.10), 100: mix(p[500], DARK_BG, 0.16), 200: mix(p[500], DARK_BG, 0.26),
    300: mix(p[500], DARK_BG, 0.42), 400: p[400], 500: p[500], 600: p[600], 700: p[300], 800: p[200], 900: p[100],
  };
  for (const s of SHADES) {
    light.push(`--${name}-${s}: ${triple(p[s])};`);
    dark.push(`--${name}-${s}: ${triple(d[s])};`);
  }
}
const tokens = {
  light: { page: "#f1f2f9", surface: "#ffffff", ink: "#121212", accent: "#7114ff", "accent-strong": "#5a0fd1", "accent-soft": "#f0e8ff" },
  dark: { page: "#121212", surface: "#18181b", ink: "#f1f2f9", accent: "#9047ff", "accent-strong": "#a66bff", "accent-soft": "#2a1647" },
};
for (const [k, v] of Object.entries(tokens.light)) light.push(`--${k}: ${triple(rgb(v))};`);
for (const [k, v] of Object.entries(tokens.dark)) dark.push(`--${k}: ${triple(rgb(v))};`);

const block = (lines) => lines.map((l) => `  ${l}`).join("\n");
const css = `/* Generated by scripts/gen-theme.mjs - do not edit by hand. */
:root {
${block(light)}
  color-scheme: light;
}
@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
${block(dark).replace(/^/gm, "  ")}
    color-scheme: dark;
  }
}
:root[data-theme="dark"] {
${block(dark)}
  color-scheme: dark;
}
`;
writeFileSync(new URL("../src/theme.css", import.meta.url), css);
console.log("wrote src/theme.css");
